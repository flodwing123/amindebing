/**
 * 按日期种子获取当日金句（每天固定50条内的伪随机顺序）
 * @param {Date} date  目标日期
 * @param {boolean} [random] 传 true 时使用随机种子（用于"换一批"，每次结果不同）
 * @returns {Array} [{cat,text}]
 */
function getDailyQuotes(date, random) {
  const seed = date.getFullYear() * 10000 + (date.getMonth() + 1) * 100 + date.getDate();
  // 简单确定性洗牌（random=true 时用当前时间做种子，保证每次换一批都不同）
  const arr = QUOTE_LIBRARY.slice();
  let s = random ? (Date.now() ^ (Math.random() * 0x7fffffff)) : seed;
  for (let i = arr.length - 1; i > 0; i--) {
    s = (s * 9301 + 49297) % 233280;
    const j = Math.floor((s / 233280) * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  // 每天固定输出 50 条（从库中按日期种子随机取 50 条）
  return arr.slice(0, 50);
}

