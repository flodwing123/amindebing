/* =========================================================
   数据管理层 · localStorage 封装
   所有数据保存在浏览器本地
   ========================================================= */
const Store = {
  _ns: "teacher_workbench_",

  get(key, def) {
    try {
      const raw = localStorage.getItem(this._ns + key);
      if (raw === null) return def;
      return JSON.parse(raw);
    } catch (e) { return def; }
  },
  set(key, val) {
    try { localStorage.setItem(this._ns + key, JSON.stringify(val)); }
    catch (e) { console.error("保存失败", e); }
  },
  del(key) {
    localStorage.removeItem(this._ns + key);
  }
};

/* 今日日期工具 */
const Today = {
  fmt(d) {
    const y = d.getFullYear(), m = String(d.getMonth() + 1).padStart(2, "0"), dd = String(d.getDate()).padStart(2, "0");
    return `${y}-${m}-${dd}`;
  },
  now() { return this.fmt(new Date()); },
  dateKey() { return this.now(); },
  parse(s) { return new Date(s); },
  addDays(d, n) { const x = new Date(d); x.setDate(x.getDate() + n); return x; }
};

